class AppError(Exception):
    """Safe, user-facing application error."""
# شرح الصنف ValidationError: يجمع البيانات والوظائف المرتبطة بهذا المكوّن.
class ValidationError(AppError): pass
# شرح الصنف NotFoundError: يجمع البيانات والوظائف المرتبطة بهذا المكوّن.
class NotFoundError(AppError): pass
# شرح الصنف DependencyError: يجمع البيانات والوظائف المرتبطة بهذا المكوّن.
class DependencyError(AppError): pass
